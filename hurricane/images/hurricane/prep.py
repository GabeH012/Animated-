# prep.py - split the two sheets into trimmed sprites, measure head / feet / bomb, write src/sprites.ts
import json, os, numpy as np, cv2
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(ROOT, 'public', 'hurricane')
os.makedirs(OUT, exist_ok=True)
PAD = 12


def components(rgba, min_area=20000):
    a = (rgba[..., 3] > 20).astype(np.uint8)
    merged = cv2.dilate(a, np.ones((25, 25), np.uint8))
    n, lab, stats, _ = cv2.connectedComponentsWithStats(merged)
    boxes = [tuple(stats[i, :4]) for i in range(1, n) if stats[i, 4] >= min_area]
    return boxes


def trim(rgba, box):
    x, y, w, h = box
    H, W = rgba.shape[:2]
    x0, y0 = max(0, x - PAD), max(0, y - PAD)
    x1, y1 = min(W, x + w + PAD), min(H, y + h + PAD)
    crop = rgba[y0:y1, x0:x1].copy()
    # keep only pixels belonging to this component (neighbours may poke into the box)
    a = (crop[..., 3] > 20).astype(np.uint8)
    merged = cv2.dilate(a, np.ones((25, 25), np.uint8))
    n, lab, stats, _ = cv2.connectedComponentsWithStats(merged)
    big = 1 + int(np.argmax(stats[1:, 4]))
    crop[lab != big, 3] = 0
    return crop


def head_of(crop):
    a8 = (crop[..., 3] > 128).astype(np.uint8)
    h, w = a8.shape
    ff = a8.copy()
    cv2.floodFill(ff, np.zeros((h + 2, w + 2), np.uint8), (0, 0), 2)
    solid = np.where(ff == 2, 0, 1).astype(np.uint8)
    dt = cv2.distanceTransform(solid, cv2.DIST_L2, 5)
    hy, hx = np.unravel_index(dt.argmax(), dt.shape)
    return [int(hx), int(hy), float(dt[hy, hx])]


def feet_of(crop):
    a = crop[..., 3] > 128
    rows = np.where(a.any(1))[0]
    bottom = rows.max()
    band = a[int(bottom - 0.035 * len(rows)):bottom + 1]
    xs = np.where(band.any(0))[0]
    return [float((xs.min() + xs.max()) / 2), float(bottom)]


def bomb_of(crop):
    rgb = crop[..., :3].astype(int)
    dark = ((rgb.max(2) < 70) & (crop[..., 3] > 200)).astype(np.uint8)
    k = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (31, 31))
    filled = cv2.morphologyEx(dark, cv2.MORPH_OPEN, k)
    n, lab, stats, cent = cv2.connectedComponentsWithStats(filled)
    if n < 2:
        return None
    i = 1 + int(np.argmax(stats[1:, 4]))
    x, y, w, h, area = stats[i]
    return [float(cent[i][0]), float(cent[i][1]), float(max(w, h))]


sprites = {}

poses = np.array(Image.open(os.path.join(HERE, 'raw', 'poses.png')).convert('RGBA'))
boxes = components(poses)
assert len(boxes) == 6, boxes
mid = poses.shape[0] / 2
top = sorted([b for b in boxes if b[1] + b[3] / 2 < mid], key=lambda b: b[0])
bot = sorted([b for b in boxes if b[1] + b[3] / 2 >= mid], key=lambda b: b[0])
for name, box in zip(['hold', 'windup', 'throw', 'smug', 'confused', 'scared'], top + bot):
    crop = trim(poses, box)
    Image.fromarray(crop).save(os.path.join(OUT, f'{name}.png'))
    s = {'w': crop.shape[1], 'h': crop.shape[0], 'head': head_of(crop), 'feet': feet_of(crop)}
    if name in ('hold', 'windup'):
        s['bomb'] = bomb_of(crop)
    sprites[name] = s

props = np.array(Image.open(os.path.join(HERE, 'raw', 'props.png')).convert('RGBA'))
boxes = sorted(components(props), key=lambda b: b[0])
assert len(boxes) == 3, boxes
for name, box in zip(['storm', 'bomb', 'palm'], boxes):
    crop = trim(props, box)
    if name == 'storm':
        # the eye of the storm: largest transparent hole near the centre
        a = (crop[..., 3] > 128).astype(np.uint8)
        h, w = a.shape
        ff = a.copy()
        cv2.floodFill(ff, np.zeros((h + 2, w + 2), np.uint8), (0, 0), 2)
        hole = (ff == 0).astype(np.uint8)
        n, lab, stats, cent = cv2.connectedComponentsWithStats(hole)
        eye = None
        if n > 1:
            i = 1 + int(np.argmax(stats[1:, 4]))
            eye = [float(cent[i][0]), float(cent[i][1]), float(np.sqrt(stats[i, 4] / np.pi))]
        semi = float(((crop[..., 3] > 10) & (crop[..., 3] < 240)).mean())
        Image.fromarray(crop).save(os.path.join(OUT, f'{name}.png'))
        sprites[name] = {'w': w, 'h': h, 'eye': eye, 'semi': semi}
        continue
    Image.fromarray(crop).save(os.path.join(OUT, f'{name}.png'))
    s = {'w': crop.shape[1], 'h': crop.shape[0]}
    if name == 'bomb':
        s['bomb'] = bomb_of(crop)
    if name == 'palm':
        s['feet'] = feet_of(crop)
    sprites[name] = s

os.makedirs(os.path.join(ROOT, 'src'), exist_ok=True)
with open(os.path.join(ROOT, 'src', 'sprites.ts'), 'w') as f:
    f.write('// generated by images/hurricane/prep.py\n')
    f.write('export const SPR = ' + json.dumps(sprites, indent=1) + ' as const;\n')
print(json.dumps(sprites, indent=1))

# QA sheet: every sprite on a coloured background with head / feet / bomb marks
tiles = []
for name, s in sprites.items():
    im = Image.open(os.path.join(OUT, f'{name}.png')).convert('RGBA')
    bg = Image.new('RGBA', im.size, (110, 190, 255, 255))
    bg.alpha_composite(im)
    arr = np.array(bg.convert('RGB'))
    if 'head' in s:
        cv2.circle(arr, tuple(map(int, s['head'][:2])), int(s['head'][2]), (255, 0, 0), 3)
    if 'feet' in s:
        cv2.circle(arr, tuple(map(int, s['feet'])), 10, (0, 200, 0), -1)
    if s.get('bomb'):
        cv2.circle(arr, tuple(map(int, s['bomb'][:2])), int(s['bomb'][2] / 2), (255, 0, 255), 3)
    if s.get('eye'):
        cv2.circle(arr, tuple(map(int, s['eye'][:2])), int(s['eye'][2]), (255, 0, 255), 3)
    t = Image.fromarray(arr)
    t.thumbnail((400, 400))
    tiles.append(t)
W = 400 * 5
sheet = Image.new('RGB', (W, 800), (40, 40, 40))
for i, t in enumerate(tiles):
    sheet.paste(t, ((i % 5) * 400, (i // 5) * 400))
sheet.save(os.path.join(HERE, 'qa', 'sprites_qa.jpg'))
